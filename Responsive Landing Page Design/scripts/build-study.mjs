// Turns study/guide.html into functions/_lib/study-page.js so the admin-only
// /admin/study route can serve it. Run after editing the guide:
//   node scripts/build-study.mjs
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const html = fs.readFileSync(path.join(root, "study/guide.html"), "utf8")
const out = `// GENERATED by scripts/build-study.mjs from study/guide.html. Do not edit by hand.
// This file exports no request handlers, so Cloudflare Pages does not turn it into a route.
export const STUDY_HTML = ${JSON.stringify(html)}
`
fs.writeFileSync(path.join(root, "functions/_lib/study-page.js"), out)
console.log(`study-page.js written (${(out.length / 1024).toFixed(0)} KB)`)
