// Bundles the ROUGE HQ app (hq/src) into functions/_lib/hq-assets.js so the protected
// /admin/hq route can serve it. The public Vite build doesn't touch any of this.
// Run after editing anything in hq/:
//   node scripts/build-hq.mjs
// Needs esbuild, react, react-dom and marked. If they aren't in node_modules, point NODE_PATH at them.
import fs from "node:fs"
import path from "node:path"
import crypto from "node:crypto"
import { fileURLToPath } from "node:url"
import { createRequire } from "node:module"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const require = createRequire(import.meta.url)
const extra = (process.env.NODE_PATH || "").split(path.delimiter).filter(Boolean)
const resolveDir = (name) => {
  for (const dir of [path.join(root, "node_modules"), ...extra]) if (fs.existsSync(path.join(dir, name))) return dir
  throw new Error(`Can't find ${name}. Install it or set NODE_PATH.`)
}
const esbuild = require(path.join(resolveDir("esbuild"), "esbuild"))

const result = await esbuild.build({
  entryPoints: [path.join(root, "hq/src/main.jsx")],
  bundle: true,
  minify: true,
  format: "iife",
  target: ["es2020", "safari15"],
  jsx: "automatic",
  define: { "process.env.NODE_ENV": '"production"' },
  nodePaths: [path.join(root, "node_modules"), ...extra],
  legalComments: "none",
  write: false,
  logLevel: "warning",
})
const js = result.outputFiles[0].text
const css = fs.readFileSync(path.join(root, "hq/src/hq.css"), "utf8")
const minCss = (await esbuild.transform(css, { loader: "css", minify: true, target: ["safari15"] })).code
const icon = fs.readFileSync(path.join(root, "hq/icon.png")).toString("base64")
const version = crypto.createHash("sha256").update(js + minCss).digest("hex").slice(0, 12)
const out = `// GENERATED by scripts/build-hq.mjs from hq/src. Do not edit by hand.
// This file exports no request handlers, so Cloudflare Pages does not turn it into a route.
export const HQ_VERSION = ${JSON.stringify(version)}
export const HQ_CSS = ${JSON.stringify(minCss)}
export const HQ_ICON = ${JSON.stringify(icon)}
export const HQ_JS = ${JSON.stringify(js)}
`
fs.writeFileSync(path.join(root, "functions/_lib/hq-assets.js"), out)
console.log(`hq-assets.js written: JS ${(js.length / 1024).toFixed(0)} KB, CSS ${(minCss.length / 1024).toFixed(0)} KB, version ${version}`)
